/**
 * **从工具定义生成参考文档**（plan §11 的 `docs/tool-reference.md` 与 `.zh-CN.md`）。
 *
 * 手写的工具文档一定会漂移：改了 schema 忘了改文档，读者看到的就是错的契约。
 * 这里换成单向生成——schema 是唯一真相，文档是它的一个视图。
 * `packages/tools/test/docs.test.ts` 会在文档过期时**直接失败**，所以漂移不可能悄悄发生。
 *
 * 生成不出来的部分（坐标口径、`fill_line` 的半径语义这类只有散文能说清的东西）
 * 留在 `plan.md` 的附录里，文档开头指过去，而不是在这里再抄一遍。
 *
 * **两份，一种语言一份。** 工具描述本身是写给 LLM 的 prompt，所以永远是英文；
 * 可读的部分（标题、分组、表头、类型名）跟语言走。两份放两个文件而不是一份两段：
 * 正文占绝大多数篇幅，塞进一份里等于把同一段英文抄两遍。
 */
export type DocLocale = 'en-US' | 'zh-CN'

export const DOC_LOCALES: readonly DocLocale[] = ['en-US', 'zh-CN']

/** 每种语言的落盘路径（相对仓库根）。 */
export const DOC_PATHS: Record<DocLocale, string> = {
  'en-US': 'docs/tool-reference.md',
  'zh-CN': 'docs/tool-reference.zh-CN.md',
}

