const SCAFFOLDS: Record<DocLocale, Scaffold> = { 'en-US': EN, 'zh-CN': ZH }

export function renderToolReference(registry: ToolRegistry, locale: DocLocale = 'en-US'): string {
  const s = SCAFFOLDS[locale]
  const tools = registry.list()
  const lines: string[] = [s.header]

  lines.push(s.atAGlance + '\n')
  lines.push(s.tableHead)
  lines.push(s.tableRule)
  for (const tool of tools) {
    lines.push(
      `| [\`${tool.name}\`](#${anchor(tool.name)}) | ${tool.mutating ? '✅' : '—'} | ${
        tool.destructive ? '⚠️' : '—'
      } | ${firstSentence(tool.description)} |`,
    )
  }
  lines.push('')

  const groups: Array<{ title: string; blurb: string; match: (tool: ToolDefinition) => boolean }> = [
    {
      title: s.batchTitle,
      blurb: s.batchBlurb,
      match: (tool) => tool.mutating && !tool.destructive && tool.name !== 'undo' && tool.name !== 'redo',
    },
    { title: s.destructiveTitle, blurb: s.destructiveBlurb, match: (tool) => tool.mutating && tool.destructive },
    { title: s.inspectTitle, blurb: s.inspectBlurb, match: (tool) => !tool.mutating },
  ]

  const grouped = new Set<string>()
  for (const group of groups) {
    const members = tools.filter((tool) => group.match(tool) && !grouped.has(tool.name))
    if (members.length === 0) continue
    lines.push(`## ${group.title}\n`)
    lines.push(`${group.blurb}\n`)
    for (const tool of members) {
      grouped.add(tool.name)
      lines.push(...renderTool(tool, s))
    }
  }

  // 兜底：上面的分组条件如果漏掉了某个工具，也要出现在文档里而不是消失
  const ungrouped = tools.filter((tool) => !grouped.has(tool.name))
  if (ungrouped.length > 0) {
    lines.push(s.other + '\n')
    for (const tool of ungrouped) lines.push(...renderTool(tool, s))
  }

  return `${lines.join('\n').trimEnd()}\n`
}

/** 校验生成的文档是否与磁盘上的一致。返回不一致的原因（空数组表示一致）。 */
export function diffToolReference(registry: ToolRegistry, onDisk: string, locale: DocLocale = 'en-US'): string[] {
  const expected = renderToolReference(registry, locale)
  if (expected === onDisk) return []
  const expectedNames = [...expected.matchAll(/^## `([a-z_]+)`$/gm)].map((match) => match[1]!)
  const diskNames = [...onDisk.matchAll(/^## `([a-z_]+)`$/gm)].map((match) => match[1]!)
  const problems: string[] = []
  const missing = expectedNames.filter((name) => !diskNames.includes(name))
  const extra = diskNames.filter((name) => !expectedNames.includes(name))
  if (missing.length > 0) problems.push(`the document is missing: ${missing.join(', ')}`)
  if (extra.length > 0) problems.push(`the document lists tools that no longer exist: ${extra.join(', ')}`)
  if (problems.length === 0) problems.push('the document differs from the generated version (a description or argument changed?)')
  return problems
}

function renderTool(tool: ToolDefinition, s: Scaffold): string[] {
  const lines: string[] = [`## \`${tool.name}\`\n`]
  lines.push(`\`\`\`\n${tool.description}\n\`\`\`\n`)

  const schema = tool.parameters
  const required = new Set(schema.required ?? [])
  const properties = schema.properties ?? {}
  const entries = Object.entries(properties)

  if (entries.length === 0) {
    lines.push(s.noArguments + '\n')
    return lines
  }

  // 先收集行、再一次性输出：中间不能插空行，否则 Markdown 会把表格截成两半
  const rows: string[] = []
  const nested: string[] = []
  for (const [name, property] of entries) {
    rows.push(
      `| \`${name}\` | ${typeOf(property, s)} | ${required.has(name) ? '✅' : '—'} | ${constraintOf(property, s)} | ${
        property.default !== undefined ? `\`${JSON.stringify(property.default)}\`` : s.none
      } | ${oneLine(property.description ?? '')} |`,
    )
    // 数组元素的对象结构单独展开——`run_batch` 的 `ops[]` 就在这一层
    const itemProperties = property.items?.properties
    if (itemProperties === undefined || Object.keys(itemProperties).length === 0) continue
    const itemRequired = new Set(property.items?.required ?? [])
    nested.push(s.eachItem(name) + '\n')
    nested.push(s.nestedHead)
    nested.push(s.nestedRule)
    for (const [key, item] of Object.entries(itemProperties)) {
      nested.push(
        `| \`${key}\` | ${typeOf(item, s)} | ${itemRequired.has(key) ? '✅' : '—'} | ${oneLine(item.description ?? '')} |`,
      )
    }
    nested.push('')
  }

  lines.push(s.argHead)
  lines.push(s.argRule)
  lines.push(...rows)
  lines.push('')
  if (nested.length > 0) lines.push(...nested)
  if (schema.additionalProperties === true) {
    lines.push(s.extraNote)
    lines.push('')
  }
  return lines
}

function typeOf(schema: JsonSchema, s: Scaffold): string {
  if (schema.enum !== undefined) return s.enumLabel
  switch (schema.type) {
    case 'array': {
      if (schema.items === undefined) return s.arrayLabel
      return schema.items.type === 'object' ? s.arrayOfObjects : `${s.arrayLabel}<${typeOf(schema.items, s)}>`
    }
    case 'integer':
    case 'number':
    case 'boolean':
    case 'object':
    case 'string':
      return s.types[schema.type] ?? s.none
    default:
      return s.none
  }
}

function constraintOf(schema: JsonSchema, s: Scaffold): string {
  const parts: string[] = []
  if (schema.enum !== undefined) parts.push(schema.enum.map((value) => `\`${String(value)}\``).join(' / '))
  if (schema.type === 'integer' || schema.type === 'number') {
    if (schema.minimum !== undefined && schema.maximum !== undefined) parts.push(`${schema.minimum}..${schema.maximum}`)
    else if (schema.minimum !== undefined) parts.push(`≥ ${schema.minimum}`)
    else if (schema.maximum !== undefined) parts.push(`≤ ${schema.maximum}`)
  }
  if (schema.type === 'array') {
    if (schema.minItems !== undefined && schema.maxItems !== undefined) parts.push(s.items(`${schema.minItems}..${schema.maxItems}`))
    else if (schema.minItems !== undefined) parts.push(`≥ ${s.items(String(schema.minItems))}`)
    else if (schema.maxItems !== undefined) parts.push(`≤ ${s.items(String(schema.maxItems))}`)
  }
  return parts.length > 0 ? parts.join(s.join) : s.none
}

/** 表格单元格里不能有换行；描述常常是多行的。 */
const oneLine = (text: string): string => text.replace(/\s*\n\s*/g, ' ').trim()

/** 描述的第一句，用在一览表里。 */
function firstSentence(description: string): string {
  const flat = oneLine(description)
  const match = /^(.+?[.。])(?:\s|$)/.exec(flat)
  const sentence = match?.[1] ?? flat
  return sentence.length > 80 ? `${sentence.slice(0, 80)}…` : sentence
}

/** GitHub 风格的锚点。 */
function anchor(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9_-]/g, '')
}
