/** 未收录字符用方块占位，避免静默画成空白让人误以为没渲染。 */
const UNKNOWN: readonly number[] = [0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f]

export interface GlyphQuery {
  /** 该字符的 7 行位掩码（低 5 位有效）。 */
  rows: readonly number[]
  width: number
  height: number
}

export function glyphFor(char: string): GlyphQuery {
  const upper = char.toUpperCase()
  return {
    rows: GLYPHS[upper] ?? GLYPHS[char] ?? UNKNOWN,
    width: GLYPH_WIDTH,
    height: GLYPH_HEIGHT,
  }
}

/**
 * 该字符是否有可用字形。
 *
 * 5×7 位图字体只覆盖 ASCII，**没有 CJK**。中文项目名直接画会变成一排"豆腐块"，
 * 所以调用方要么把文字约束成 ASCII，要么先过 `sanitizeForFont`。
 */
export function isRenderable(char: string): boolean {
  return GLYPHS[char.toUpperCase()] !== undefined || GLYPHS[char] !== undefined
}

/** 把不可渲染的字符替换成 `?`（避免整段文字变成一排方块）。 */
export function sanitizeForFont(text: string): string {
  let out = ''
  for (const char of text) out += isRenderable(char) ? char : '?'
  return out
}

/** 一段文字渲染后的像素宽度。 */
export function textWidth(text: string, scale = 1): number {
  return Math.max(0, text.length * CHAR_WIDTH - 1) * scale
}

/** 一段文字渲染后的像素高度。 */
export function textHeight(scale = 1): number {
  return GLYPH_HEIGHT * scale
}
