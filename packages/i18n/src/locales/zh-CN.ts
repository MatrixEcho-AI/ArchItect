export type Resources = typeof zhCN

/** 把字面量类型放宽成 `string`，这样别的语言表只要**结构相同**即可（不必逐字相同）。 */
export type DeepStrings<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepStrings<T[K]>
}

/** 语言表的结构契约。`en-US` 用它做 `satisfies`，缺键/多键都是编译错误。 */
export type Messages = DeepStrings<Resources>

/** 点分路径形式的文案键，如 `'chat.placeholder'`。写错键编译不过。 */
export type MessageKey<T = Resources, Prefix extends string = ''> = {
  [K in keyof T & string]: T[K] extends string ? `${Prefix}${K}` : MessageKey<T[K], `${Prefix}${K}.`>
}[keyof T & string]
